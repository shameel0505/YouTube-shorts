import os
import json
import subprocess
import google.generativeai as genai
import dotenv

# Load environment variables
dotenv.load_dotenv(os.path.join(os.path.dirname(__file__), "..", ".env"))

GEMINI_API_KEY = os.environ.get("GEMINI_API_KEY")
if not GEMINI_API_KEY:
    print("❌ Error: GEMINI_API_KEY not found in .env")
    exit(1)

genai.configure(api_key=GEMINI_API_KEY)
model = genai.GenerativeModel("gemini-2.5-flash")

print("📝 Asking Gemini to generate a fresh script with 10 B-roll scenes and native narration lines...")

prompt = """
You are a master YouTube Shorts director, cinematographer, and educational scriptwriter.
We need an incredibly "WOW", mind-blowing, and visually stunning 60-second script about a fascinating scientific or historical anomaly. 
Do NOT use space facts. Pick something earthy, biological, or physics-related that is highly cinematic.
(Specifically, write about either: 
1. The terrifying reality of Deep-Sea Gigantism in the Mariana Trench (bizarre, massive, alien-like creatures living in crushing darkness).
2. The "Wood-Wide Web" (the hidden, glowing, Avatar-like mycelial network that connects entire forests, allowing trees to communicate and share resources).
3. The Observer Effect / Double Slit Experiment (the mind-bending quantum reality that particles behave differently simply because they are being watched, suggesting our reality might be a simulation).
Pick whichever one you can make the most cinematic and awe-inspiring.

We need exactly 10 visual scenes (B-roll prompts) to accompany the script. 
CRITICAL: You are acting as the Creative Director. Your visual prompts MUST be extremely long, hyper-detailed, and cinematic. Do not just say "A black hole". You must describe the lighting, the camera angle, the lens (e.g. IMAX 70mm, macro lens), and the atmosphere in rich detail.

You must also break your narration down so that exactly ONE line of narration accompanies each visual scene.

Respond ONLY with a strict JSON object (no markdown, no backticks).
Format:
{
  "topic": "The exact scientific topic",
  "title": "A catchy, mind-blowing YouTube Short title",
  "scenes": [
    {
      "action": "A hyper-realistic, highly detailed cinematic shot of... [describe lighting, camera movement, aesthetic, hyper-detailed]",
      "line": "The exact line of narration that the voiceover will speak during this scene."
    },
    ... exactly 10 scenes in total.
  ]
}
"""

response = model.generate_content(prompt)
text = response.text.strip()
if text.startswith("```json"):
    text = text[7:]
if text.startswith("```"):
    text = text[3:]
if text.endswith("```"):
    text = text[:-3]

try:
    data = json.loads(text.strip())
except json.JSONDecodeError as e:
    print("❌ Failed to parse Gemini output as JSON:")
    print(text)
    exit(1)

print(f"✅ Generated script for: {data['title']}")

# We will generate a movie.toml file
movie_toml_content = f"""# movie.toml — Auto-generated by generate_movie.py
schema_version = 1
title = "{data['title']}"
project = "f73aac02-d5f5-4b72-a52a-00e0c7d01991"
output_dir = "./output/experiments/my_movie"

[style]
look = "cinematic, documentary style"
negative = "text, watermark, low quality, cartoon"
suffix = "hyper-realistic, highly detailed, professional cinematography, IMAX 70mm."

[[characters]]
name = "Narrator"
appearance = "A cosmic entity"
voice = "Charon"

"""

print("\\n--- SCRIPT PREVIEW ---")
# Ensure exactly 10 scenes (or however many Gemini returned)
for i, scene in enumerate(data['scenes']):
    action_text = scene['action'].replace('"', '')
    line_text = scene['line'].replace('"', '')
    print(f"Scene {i+1}:")
    print(f"  Visual: {action_text}")
    print(f"  Audio:  {line_text}")
    
    movie_toml_content += f"""
[[scenes]]
id = "scene_{i+1}"
action = "{action_text}"
framing = "wide"
aspect = "9:16"
characters = ["Narrator"]
speaker = "Narrator"
line = "{line_text}"
"""

movie_toml_path = os.path.join(os.path.dirname(__file__), "movie.toml")
with open(movie_toml_path, "w") as f:
    f.write(movie_toml_content)

print(f"\\n✅ Generated movie.toml at {movie_toml_path}")

print("\\n" + "="*50)
print("🛑 PAUSING SO YOU CAN REVIEW THE SCRIPT 🛑")
print("="*50)
input("Press ENTER to start the video generation, or Ctrl+C to cancel...")

# Run gflow movie run
print("🎬 Launching gflow movie run...")
print("This will take a while. It is going to generate", len(data['scenes']), "clips with baked-in Google Flow narration!")

cmd = ["gflow", "movie", "run", movie_toml_path, "--yes"]
env = os.environ.copy()
env["GFLOW_CLI_HEADLESS"] = "0"
env["GFLOW_CLI_GEMINI_API_KEY"] = GEMINI_API_KEY
    
try:
    subprocess.run(cmd, env=env, check=True)
    print("🎉 gflow movie run completed! All clips generated successfully.")
    
    # --- NEW: Custom Stitch & Add Subtitles ---
    print("\n✍️ Stitching clips and generating subtitles...")
    
    import sys, json
    sys.path.append(os.path.join(os.path.dirname(__file__), ".."))
    from video.captions import transcribe_audio
    from video.editor import _build_caption_clips
    from moviepy.editor import VideoFileClip, CompositeVideoClip, concatenate_videoclips
    
    output_dir = "./output/experiments/my_movie"
    handoff_path = os.path.join(os.path.dirname(__file__), "movie-handoff.json")
    
    if os.path.exists(handoff_path):
        with open(handoff_path, "r") as f:
            handoff = json.load(f)
            
        # 1. Gather the 10 clips in order
        clip_paths = []
        for c in handoff.get("clips", []):
            if c.get("file"):
                clip_paths.append(os.path.join(output_dir, c["file"]))
                
        if clip_paths:
            print(f"🔗 Found {len(clip_paths)} clips, concatenating...")
            video_clips = [VideoFileClip(p) for p in clip_paths]
            stitched_video = concatenate_videoclips(video_clips, method="compose")
            
            # 2. Extract Audio for Whispers
            temp_audio = os.path.join(output_dir, "temp_extracted_audio.wav")
            stitched_video.audio.write_audiofile(temp_audio, fps=44100, logger=None)
            
            # 3. Transcribe
            captions = transcribe_audio(temp_audio, words_per_caption=4)
            
            # 4. Build Caption Overlays
            caption_clips = _build_caption_clips(captions, stitched_video, fmt=1)
            
            # 5. Composite and Export
            final_video = CompositeVideoClip([stitched_video] + caption_clips)
            final_output_path = os.path.join(output_dir, "final_narrated_subtitled.mp4")
            
            print(f"🎞️ Burning subtitles into {final_output_path}...")
            final_video.write_videofile(
                final_output_path,
                fps=30,
                codec="libx264",
                audio_codec="aac",
                preset="ultrafast",
                logger=None
            )
            print(f"🎬 ABSOLUTE PERFECTION! Your final stitched video with Voice AND Subtitles is ready at: {final_output_path}")
            
            # Cleanup
            os.remove(temp_audio)
            for c in video_clips: c.close()
            stitched_video.close()
        else:
            print("⚠️ No clips found in movie-handoff.json")
    else:
        print("⚠️ Could not find movie-handoff.json to stitch clips!")

except subprocess.CalledProcessError as e:
    print(f"❌ Process failed with exit code: {e.returncode}")
